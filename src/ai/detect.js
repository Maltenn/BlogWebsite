// The AI-writing detector, behind one adapter (docs/decisions/002):
//
//   detect(env, text) → null (switched off) | { score: 0..1 (higher = more likely AI), label: 'AI' | 'Mixed' | 'Human' |
//                       'Unknown', model: '<provider>:<model>', raw } | { error }
//
// AI_DETECTOR picks the provider: off (the default) | mock | workersai | pangram | gptzero. Keys are secrets
// (PANGRAM_API_KEY, GPTZERO_API_KEY). Every failure (no key, an error answer, a timeout) comes back as { error }: the
// post stays up and nothing happens (fail open). The Worker and tools/eval-detector.mjs both call this.
//
//   mock       for the tests, the demo and trying the evaluation harness: a text containing "mock-ai-score: 0.97" gets
//              that score; anything else gets a toy score from stock "AI phrases" per 100 words. Not a real detector.
//   workersai  Cloudflare Workers AI, the free option (a daily allocation of free neurons). Workers AI has no AI-text
//              classifier and no documented token log-probabilities (decision 002), so a perplexity method (Binoculars,
//              Fast-DetectGPT) can't be built on it. What's left is asking an instruction model to judge
//              (AI_DETECTOR_MODEL, default @cf/meta/llama-3.1-8b-instruct), which the research finds unreliable. It
//              is wired up so it can be measured with the evaluation harness; expect it to fail the 1% bar, and keep it
//              in shadow mode. It needs the AI binding (wrangler.jsonc, commented out: it needs a Cloudflare login even
//              locally) or, for the harness, CF_ACCOUNT_ID + CF_API_TOKEN.
//   pangram    Pangram's API (decision 002's pick). PANGRAM_API_KEY; PANGRAM_URL overrides the endpoint. The field names
//              (fraction_ai / prediction_short) are from their docs as read in 002 and not yet checked against a live
//              key: run the harness first.
//   gptzero    GPTZero's v2 API (decision 002's fallback). GPTZERO_API_KEY. Same caveat.

export const DETECTORS = ['off', 'mock', 'workersai', 'pangram', 'gptzero'];
export const detectorName = env => {
  const n = String((env && env.AI_DETECTOR) || 'off').trim().toLowerCase();
  return DETECTORS.includes(n) ? n : 'off';
};

const TIMEOUT = 10000;
export const labelFor = score => (score >= 0.95 ? 'AI' : score >= 0.5 ? 'Mixed' : 'Human');

/* ---------------------------------------------------------------- mock */

const TELLS = ['delve', 'tapestry', 'testament to', 'it\'s important to note', 'it is important to note', 'in conclusion',
  'furthermore', 'moreover', 'additionally', 'fast-paced', 'navigate the', 'landscape', 'realm', 'embark', 'foster',
  'vibrant', 'seamless', 'unlock', 'elevate', 'resonate', 'nuanced', 'multifaceted', 'pivotal', 'crucial', 'ever-evolving',
  'in summary', 'it is worth noting', 'whether you\'re', 'serves as', 'plays a crucial role', 'boasts', 'showcasing',
  'underscores', 'intricate', 'holistic', 'leverage', 'robust', 'journey', 'transformative', 'invaluable', 'a myriad of',
  'in today\'s', 'remember,', 'ultimately,', 'not only', 'but also', 'empower', 'cutting-edge', 'game-changer'];

export function mockDetect(text) {
  const marker = /mock-ai-score[:=]\s*(1(?:\.0+)?|0(?:\.\d+)?)/i.exec(text);
  if (marker) {
    const score = Number(marker[1]);
    return { score, label: labelFor(score), model: 'mock:marker', raw: { marker: true } };
  }
  const low = text.toLowerCase().replace(/’/g, '\'');
  const words = (low.match(/\p{L}+/gu) || []).length || 1;
  let hits = 0;
  for (const t of TELLS) hits += low.split(t).length - 1;
  const density = (hits / words) * 100;
  const score = Math.round((1 - Math.exp(-0.75 * density)) * 1000) / 1000;
  return { score, label: labelFor(score), model: 'mock:tells-1', raw: { hits, words } };
}

/* ----------------------------------------------------------- workersai */

const JUDGE = 'You check whether text was written by an AI language model or by a person. Read the text and reply with ' +
  'only a JSON object like {"ai_probability": 0.12}, where ai_probability is your estimate from 0 to 1 that the text was ' +
  'generated by an AI. No other words.';

export function parseProbability(s) {
  const m = /"?ai_probability"?\s*[:=]\s*([01](?:\.\d+)?|\.\d+)/i.exec(String(s)) || /\b(0(?:\.\d+)?|1(?:\.0+)?)\b/.exec(String(s));
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isFinite(n) && n >= 0 && n <= 1 ? n : null;
}

async function workersAi(env, text, f) {
  const model = env.AI_DETECTOR_MODEL || '@cf/meta/llama-3.1-8b-instruct';
  const input = { messages: [{ role: 'system', content: JUDGE }, { role: 'user', content: text }], max_tokens: 24, temperature: 0 };
  let out;
  if (env.AI && typeof env.AI.run === 'function') out = await env.AI.run(model, input);
  else if (env.CF_ACCOUNT_ID && env.CF_API_TOKEN) {
    const r = await f(`https://api.cloudflare.com/client/v4/accounts/${env.CF_ACCOUNT_ID}/ai/run/${model}`, {
      method: 'POST', headers: { Authorization: `Bearer ${env.CF_API_TOKEN}`, 'Content-Type': 'application/json' },
      body: JSON.stringify(input), signal: AbortSignal.timeout(TIMEOUT),
    });
    if (!r.ok) throw new Error('workers ai ' + r.status);
    out = (await r.json()).result;
  } else throw new Error('no AI binding (and no CF_ACCOUNT_ID / CF_API_TOKEN)');
  const score = parseProbability(out && (out.response ?? out));
  if (score == null) throw new Error('unreadable answer');
  return { score, label: labelFor(score), model: 'workersai:' + model, raw: { response: String(out.response ?? '').slice(0, 200) } };
}

/* ------------------------------------------------------ pangram, gptzero */

async function pangram(env, text, f) {
  if (!env.PANGRAM_API_KEY) throw new Error('PANGRAM_API_KEY is not set');
  const r = await f(env.PANGRAM_URL || 'https://text.api.pangram.com', {
    method: 'POST', headers: { 'Content-Type': 'application/json', 'x-api-key': env.PANGRAM_API_KEY },
    body: JSON.stringify({ text }), signal: AbortSignal.timeout(TIMEOUT),
  });
  if (!r.ok) throw new Error('pangram ' + r.status);
  const d = await r.json();
  const score = Number(d.fraction_ai ?? d.ai_likelihood);
  if (!Number.isFinite(score)) throw new Error('pangram: no score');
  const short = String(d.prediction_short || d.prediction || '').toLowerCase();
  const label = short === 'ai' ? 'AI' : short.includes('mixed') || short.includes('assist') ? 'Mixed' : short === 'human' ? 'Human' : labelFor(score);
  return { score, label, model: 'pangram:' + (d.version || env.PANGRAM_MODEL || 'default'), raw: { fraction_ai: d.fraction_ai, prediction_short: d.prediction_short } };
}

async function gptzero(env, text, f) {
  if (!env.GPTZERO_API_KEY) throw new Error('GPTZERO_API_KEY is not set');
  const r = await f('https://api.gptzero.me/v2/predict/text', {
    method: 'POST', headers: { 'Content-Type': 'application/json', 'x-api-key': env.GPTZERO_API_KEY },
    body: JSON.stringify({ document: text }), signal: AbortSignal.timeout(TIMEOUT),
  });
  if (!r.ok) throw new Error('gptzero ' + r.status);
  const d = await r.json();
  const doc = (d.documents || [])[0] || {};
  const score = Number((doc.class_probabilities && doc.class_probabilities.ai) ?? doc.completely_generated_prob);
  if (!Number.isFinite(score)) throw new Error('gptzero: no score');
  const cls = String(doc.predicted_class || '').toLowerCase();
  const label = cls === 'ai' ? 'AI' : cls === 'mixed' ? 'Mixed' : cls === 'human' ? 'Human' : labelFor(score);
  return { score, label, model: 'gptzero:' + (d.version || 'v2'), raw: { predicted_class: doc.predicted_class, score } };
}

const PROVIDERS = { mock: async (env, text) => mockDetect(text), workersai: workersAi, pangram, gptzero };

export async function detect(env, text, { fetchImpl = fetch } = {}) {
  const name = detectorName(env);
  if (name === 'off') return null;
  try {
    const out = await PROVIDERS[name](env, text, fetchImpl);
    return { ...out, score: Math.max(0, Math.min(1, out.score)) };
  } catch (e) {
    return { error: String((e && e.message) || e).slice(0, 200), model: name };
  }
}
