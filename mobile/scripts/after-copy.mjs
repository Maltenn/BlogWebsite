// Runs after every `cap copy` / `cap sync` (npm script "capacitor:copy:after"). It adds the three things that depend on the
// build-time settings to the platform copies of the web bundle. It never touches ../public.
//   native-config.json   what public/js/core/native.js reads once at start-up (the API origin)
//   index.html           the same file with the app's Content-Security-Policy as a <meta> tag (see config.cjs)
//   ios/App/App/App.entitlements   push, and associated domains for the origin's host
import { createRequire } from 'node:module';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const cfg = require('./config.cjs');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const targets = [
  join(root, 'android', 'app', 'src', 'main', 'assets', 'public'),
  join(root, 'ios', 'App', 'App', 'public'),
].filter(existsSync);

for (const dir of targets) {
  writeFileSync(join(dir, 'native-config.json'), JSON.stringify({ origin: cfg.origin, appId: cfg.appId, appName: cfg.appName }, null, 2) + '\n');

  const file = join(dir, 'index.html');
  let html = readFileSync(file, 'utf8');
  html = html.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>\s*/g, '');            // (a re-run replaces, never stacks)
  const meta = `<meta http-equiv="Content-Security-Policy" content="${cfg.csp().replace(/"/g, '&quot;')}">`;
  if (!/<meta charset="UTF-8">/.test(html)) throw new Error('index.html changed: after-copy.mjs expects <meta charset="UTF-8"> to put the CSP after');
  html = html.replace('<meta charset="UTF-8">', `<meta charset="UTF-8">\n    ${meta}`);
  writeFileSync(file, html);
  console.log(`[ourspace] ${dir}: native-config.json (origin ${cfg.origin}) + CSP meta`);
}

// iOS entitlements. aps-environment: Xcode swaps "development" for "production" when it signs for the App Store.
// applinks: only for a real https host (an http://localhost origin has no universal links).
const iosApp = join(root, 'ios', 'App', 'App');
if (existsSync(iosApp)) {
  const host = new URL(cfg.origin).hostname;
  const domains = cfg.secure && host !== 'localhost'
    ? `\t<key>com.apple.developer.associated-domains</key>\n\t<array>\n\t\t<string>applinks:${host}</string>\n\t\t<string>webcredentials:${host}</string>\n\t</array>\n`
    : '';
  writeFileSync(join(iosApp, 'App.entitlements'), `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- GENERATED by mobile/scripts/after-copy.mjs from the build-time origin. Do not edit. -->
<plist version="1.0">
<dict>
\t<key>aps-environment</key>
\t<string>development</string>
${domains}</dict>
</plist>
`);
}
